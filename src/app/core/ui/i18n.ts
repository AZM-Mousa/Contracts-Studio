@Service()
export class I18n {
  readonly #prefs = inject(Preferences);
  readonly #dict = computed(() => (this.#prefs.lang() === 'ar' ? AR : EN));

  t(key: Key, params?: Record<string, string | number>): string {
    let text: string = this.#dict()[key];
    for (const [k, v] of Object.entries(params ?? {})) {
      text = text.replace(`{${k}}`, String(this.#format(v)));
    }
    return text;
  }

  field(type: string): string {
    return FIELD_NAMES[type]?.[this.#prefs.lang() === 'ar' ? 1 : 0] ?? type;
  }

  group(group: string): string {
    return GROUP_NAMES[group]?.[this.#prefs.lang() === 'ar' ? 1 : 0] ?? group;
  }

  #format(value: string | number): string {
    return typeof value === 'number' ? value.toLocaleString(this.#prefs.lang() === 'ar' ? 'ar-SA' : 'en-US') : value;
  }
}
